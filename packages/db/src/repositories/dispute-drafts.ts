// M2-07: `dispute_drafts`, one row per (dispute, pack scope check version, filing action). The drafting job
// writes the row with its compiled blob and its proposal in one transaction (the caller's); a re-delivered
// trigger finds the row by `findForKey` and writes nothing. `too_late` and the drafting failures are
// `audit_log` entries (no draft row), read back by `outcomeRecorded` so a re-delivery records nothing twice.
import type { ActionKind, WorkspaceId } from "@cleared/core";
import { and, desc, eq, ne, sql } from "drizzle-orm";
import type { Db } from "../client.ts";
import type { Executor, Tx } from "../tx.ts";
import { auditLog, disputeDrafts, disputes } from "../../schema/index.ts";

export type DisputeDraftRow = typeof disputeDrafts.$inferSelect;

/** A fact ref as stored: what one paragraph of the notes relies on. */
export interface StoredFactRef {
  readonly ref: string;
  readonly kind: "item" | "fact" | "line" | "quote";
  /** the evidence item behind the ref (null for a scope line) */
  readonly evidence_item_id: string | null;
}

export interface NewDisputeDraft {
  /** generated by the caller: the filing payload carries it before the row exists */
  readonly id: string;
  /** our `disputes.id` */
  readonly disputeId: string;
  readonly packId: string;
  readonly checkVersion: number;
  readonly actionKind: Extract<ActionKind, "provide_evidence" | "provide_supporting_info">;
  readonly evidenceType: string;
  readonly reasonUnmapped: boolean;
  readonly notes: string;
  readonly evidenceItemIds: readonly string[];
  readonly factRefs: readonly { readonly paragraph: number; readonly refs: readonly StoredFactRef[] }[];
  readonly compiledBlobId: string;
  /** canonicalHash of the filing payload */
  readonly sha256: string;
  readonly runId: string;
  readonly proposedActionId: string;
}

/** The outcomes recorded without a draft row (`audit_log.action`). */
export const DRAFT_AUDIT_ACTIONS = {
  tooLate: "dispute_draft.too_late",
  unavailable: "dispute_draft.unavailable",
} as const;

export function disputeDraftsRepo(db: Db, workspaceId: WorkspaceId) {
  const ws = workspaceId;
  return {
    /** Serialises drafting per dispute for the transaction (row lock on our `disputes` row). */
    async lockDispute(disputeId: string, tx: Tx): Promise<boolean> {
      const rows = await tx
        .select({ id: disputes.id })
        .from(disputes)
        .where(and(eq(disputes.workspaceId, ws), eq(disputes.id, disputeId)))
        .for("update");
      return rows.length === 1;
    },

    async findForKey(
      disputeId: string,
      checkVersion: number,
      actionKind: string,
      tx?: Executor,
    ): Promise<DisputeDraftRow | null> {
      const rows = await (tx ?? db)
        .select()
        .from(disputeDrafts)
        .where(
          and(
            eq(disputeDrafts.workspaceId, ws),
            eq(disputeDrafts.disputeId, disputeId),
            eq(disputeDrafts.checkVersion, checkVersion),
            sql`${disputeDrafts.actionKind}::text = ${actionKind}`,
          ),
        )
        .limit(1);
      return rows[0] ?? null;
    },

    /** Inserts in the caller's transaction; throws on a duplicate key (the caller holds `lockDispute`). */
    async insert(d: NewDisputeDraft, tx: Tx): Promise<DisputeDraftRow> {
      const rows = await tx
        .insert(disputeDrafts)
        .values({
          id: d.id,
          workspaceId: ws,
          disputeId: d.disputeId,
          packId: d.packId,
          checkVersion: d.checkVersion,
          actionKind: d.actionKind,
          evidenceType: d.evidenceType,
          reasonUnmapped: d.reasonUnmapped,
          notes: d.notes,
          evidenceItemIds: [...d.evidenceItemIds],
          factRefs: d.factRefs,
          compiledBlobId: d.compiledBlobId,
          sha256: d.sha256,
          runId: d.runId,
          proposedActionId: d.proposedActionId,
        })
        .returning();
      const row = rows[0];
      if (!row) throw new Error("dispute_drafts insert returned no row");
      return row;
    },

    /** Newest first. */
    async listForDispute(disputeId: string, tx?: Executor): Promise<DisputeDraftRow[]> {
      return (tx ?? db)
        .select()
        .from(disputeDrafts)
        .where(and(eq(disputeDrafts.workspaceId, ws), eq(disputeDrafts.disputeId, disputeId)))
        .orderBy(desc(disputeDrafts.createdAt));
    },

    /** The workspace's unresolved disputes on one payment (a `pack.checked` finds what to draft for). */
    async openDisputesForPayment(paymentId: string, tx?: Executor) {
      return (tx ?? db)
        .select()
        .from(disputes)
        .where(
          and(
            eq(disputes.workspaceId, ws),
            eq(disputes.paymentId, paymentId),
            ne(disputes.status, "RESOLVED"),
          ),
        );
    },

    /** An outcome already recorded for this (dispute, check version, action) key. */
    async outcomeRecorded(
      action: string,
      key: { readonly disputeId: string; readonly checkVersion: number; readonly actionKind: string },
      tx?: Executor,
    ): Promise<boolean> {
      const rows = await (tx ?? db)
        .select({ id: auditLog.id })
        .from(auditLog)
        .where(
          and(
            eq(auditLog.workspaceId, ws),
            eq(auditLog.action, action),
            sql`${auditLog.detail}->>'disputeId' = ${key.disputeId}`,
            sql`(${auditLog.detail}->>'checkVersion')::int = ${key.checkVersion}`,
            sql`${auditLog.detail}->>'actionKind' = ${key.actionKind}`,
          ),
        )
        .limit(1);
      return rows.length > 0;
    },
  };
}

export type DisputeDraftsRepo = ReturnType<typeof disputeDraftsRepo>;
