// Scope snapshot (M3-07, ADR 0018): a fixed, hash-identified PDF of the pack's agreed scope, its payment, the
// delivery evidence metadata and the client's acknowledgement (if any). It is a "scope snapshot", never
// "signed": seller text plus an optional buyer acknowledgement, not a signature (B6 #9).
// This module is the content model only: what goes in, the input hash that makes the job idempotent, and
// the fixed wording. Rendering (pdf-lib) lives in packages/adapters; the job in apps/worker.
import { z } from "zod";
import { canonicalHash } from "../agent/canonical-hash.ts";
import { Sha256Schema, type Sha256 } from "../ids.ts";
import { EVIDENCE_KINDS, type EvidenceKind } from "./evidence.ts";

/**
 * Kinds Cleared writes itself from records it already holds (M3-06 acknowledgement, M3-07 snapshot). They
 * are records, not new facts: the AI never extracts or checks them (BL-01 6569233018, ADR 0018).
 */
export const CLEARED_EVIDENCE_KINDS = [
  "client_ack",
  "scope_snapshot",
] as const satisfies readonly EvidenceKind[];
export type ClearedEvidenceKind = (typeof CLEARED_EVIDENCE_KINDS)[number];
export const isClearedEvidenceKind = (kind: string): kind is ClearedEvidenceKind =>
  (CLEARED_EVIDENCE_KINDS as readonly string[]).includes(kind);

/** Pack items listed under "Delivery evidence" (metadata only: kind, created_at, sha256). */
export const SCOPE_SNAPSHOT_DELIVERY_KINDS = [
  "delivery",
  "shipment",
] as const satisfies readonly EvidenceKind[];

export const SCOPE_SNAPSHOT_TITLE = "Scope snapshot";
export const SCOPE_SNAPSHOT_NOT_ACKNOWLEDGED = "Not acknowledged by the client";
/** The only place the words "signed" / "signature" may appear in the document (and only negated). */
export const SCOPE_SNAPSHOT_FOOTER =
  "Generated by Cleared from seller-provided text and recorded acknowledgements. This is not a signature or a contract.";

const Iso = z.iso.datetime();

/** Everything the snapshot prints except `generatedAt`: the input of the idempotency hash. */
export const ScopeSnapshotContentSchema = z.strictObject({
  packId: z.uuid(),
  payment: z.strictObject({
    captureId: z.string().min(1),
    /** decimal string as stored (e.g. "64.00") */
    amount: z.string().min(1),
    currency: z.string().length(3),
    /** when Cleared recorded the payment (ISO 8601 UTC) */
    date: Iso,
  }),
  scope: z.strictObject({
    itemId: z.uuid(),
    sha256: Sha256Schema,
    /** verbatim; null when the scope is a file without a text layer */
    text: z.string().nullable(),
  }),
  delivery: z.array(
    z.strictObject({
      kind: z.enum(EVIDENCE_KINDS),
      createdAt: Iso,
      sha256: Sha256Schema,
    }),
  ),
  /** the acknowledgement of this scope item (bound by `scope_sha256`), or null */
  ack: z
    .strictObject({
      typedName: z.string(),
      acceptedAt: Iso,
      ip: z.string(),
      userAgent: z.string(),
      /** the `client_ack` evidence item's sha256 */
      sha256: Sha256Schema,
    })
    .nullable(),
  /** the seller's IANA time zone, for the acknowledgement's local time */
  timeZone: z.string().min(1),
});
export type ScopeSnapshotContent = z.infer<typeof ScopeSnapshotContentSchema>;

export interface ScopeSnapshotDocument extends ScopeSnapshotContent {
  /** ISO 8601 UTC; printed and used as the PDF creation date, so equal inputs give equal bytes */
  readonly generatedAt: string;
}

/** The job's idempotency key per pack: equal content → the existing snapshot, never a second one. */
export function scopeSnapshotInputHash(content: ScopeSnapshotContent): Sha256 {
  return canonicalHash(ScopeSnapshotContentSchema.parse(content));
}

/** `scope_snapshot.render` job payload (seller button, or a `client_ack` arriving). */
export const ScopeSnapshotRenderJobSchema = z.strictObject({
  workspaceId: z.uuid(),
  packId: z.uuid(),
});
export type ScopeSnapshotRenderJob = z.infer<typeof ScopeSnapshotRenderJobSchema>;
